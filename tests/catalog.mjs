import assert from 'node:assert/strict';
import ts from 'typescript';
import {DatabaseSync} from 'node:sqlite';
import {drizzle} from 'drizzle-orm/sqlite-proxy';
import {readFileSync,readdirSync} from 'node:fs';
const compile=s=>'data:text/javascript;base64,'+Buffer.from(ts.transpileModule(s,{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText).toString('base64');
const modulesUrl=compile(readFileSync('lib/modules.ts','utf8'));
const schemaUrl=compile(readFileSync('db/schema.ts','utf8').replace("'drizzle-orm/sqlite-core'",JSON.stringify(import.meta.resolve('drizzle-orm/sqlite-core'))));
const schema=await import(schemaUrl);
const sqlite=new DatabaseSync(':memory:');
const migrations=readdirSync('drizzle').filter(f=>f.endsWith('.sql')).sort();
// Apply the earlier schema, retain a legacy record, then migrate to Product.
for(const f of migrations.slice(0,-1))sqlite.exec(readFileSync('drizzle/'+f,'utf8'));
sqlite.exec("INSERT INTO tickets(title,type,status,priority,module,assignee,description,expected,actual,steps,release,due,created,updated) VALUES('Existing ticket','Bug','Triage','High','Case Sheet','','Existing description','','','','','','2026-10-17','2026-10-17')");
sqlite.exec(readFileSync('drizzle/'+migrations.at(-1),'utf8'));
assert.equal(sqlite.prepare('SELECT product FROM tickets').get().product,'Clinic App');
const db=drizzle(async(sql,params,method)=>{const statement=sqlite.prepare(sql);if(method==='run'){statement.run(...params);return {rows:[]};}statement.setReturnArrays(true);return {rows:statement.all(...params)};},{schema});
globalThis.catalogTestDb=db;
const source=readFileSync('lib/catalog.ts','utf8').replace("import {getDb} from '@/db';","const getDb=()=>globalThis.catalogTestDb;").replace("'@/db/schema'",JSON.stringify(schemaUrl)).replace("'./modules'",JSON.stringify(modulesUrl));
const {getCatalog,addCatalogOption,optionName}=await import(compile(source));
assert.deepEqual((await getCatalog()).products,['Clinic App','Lab App','CRM App']);
assert.equal((await addCatalogOption('product','','clinic app','QA')).added,false);
const p=await addCatalogOption('product','','Partner App','QA');assert.ok(p.catalog.products.includes('Partner App'));
await addCatalogOption('module','Lab App','Order Tracking','QA');
const repeat=await addCatalogOption('module','lab app',' order   tracking ','QA');assert.equal(repeat.added,false);assert.equal(repeat.name,'Order Tracking');
await addCatalogOption('module','CRM App','Order Tracking','QA');
const catalog=await getCatalog();assert.ok(catalog.modulesByProduct['Lab App'].includes('Order Tracking'));assert.ok(!catalog.modulesByProduct['Clinic App'].includes('Order Tracking'));
assert.equal(sqlite.prepare("SELECT count(*) AS n FROM catalog_options WHERE kind='module'").get().n,2);
await assert.rejects(()=>addCatalogOption('module','Missing App','Order Tracking','QA'));
for(const name of ['', 'x', 'x'.repeat(81),'bad\u0000name'])assert.throws(()=>optionName(name));
const model=await import(compile(readFileSync('lib/model.ts','utf8').replaceAll("'./modules'",JSON.stringify(modulesUrl))));
const valid={...model.blank,title:'Test product module pairing',description:'A meaningful test description',product:'Lab App',module:'Order Tracking'};
assert.equal(model.validateTicket(valid,catalog).module,'Order Tracking');
assert.throws(()=>model.validateTicket({...valid,product:'Clinic App'},catalog));
assert.throws(()=>model.validateTicket({...valid,module:'Unregistered'},catalog));
assert.throws(()=>model.validateTicket({...valid,module:''},catalog));
console.log('Product migration preserves existing tickets; durable additions, case-insensitive deduplication and product/module validation passed.');
sqlite.close();delete globalThis.catalogTestDb;
